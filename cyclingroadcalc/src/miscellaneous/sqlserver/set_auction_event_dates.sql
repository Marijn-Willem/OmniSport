DECLARE @season NVARCHAR(4)
DECLARE @season_id INT

SET @season = '2026'

SELECT @season_id = id FROM season WHERE name = @season

UPDATE compseason
SET startdate = CASE @season
WHEN '2024' THEN CASE competitionid
    WHEN 1 THEN '2024-02-24'
    WHEN 2 THEN '2024-02-25'
    WHEN 3 THEN '2024-03-02'
    WHEN 4 THEN '2024-03-16'
    WHEN 5 THEN '2024-03-20'
    WHEN 6 THEN '2024-03-22'
    WHEN 7 THEN '2024-03-24'
    WHEN 8 THEN '2024-03-27'
    WHEN 9 THEN '2024-03-31'
    WHEN 10 THEN '2024-04-03'
    WHEN 11 THEN '2024-04-07'
    WHEN 12 THEN '2024-04-10'
    WHEN 13 THEN '2024-04-14'
    WHEN 14 THEN '2024-04-17'
    WHEN 15 THEN '2024-04-21'
    END
WHEN '2025' THEN CASE competitionid
    WHEN 1 THEN '2025-03-01'
    WHEN 2 THEN '2025-03-02'
    WHEN 3 THEN '2025-03-08'
    WHEN 4 THEN '2025-03-22'
    WHEN 5 THEN '2025-03-26'
    WHEN 6 THEN '2025-03-28'
    WHEN 7 THEN '2025-03-30'
    WHEN 8 THEN '2025-04-02'
    WHEN 9 THEN '2025-04-06'
    WHEN 10 THEN '2025-04-09'
    WHEN 11 THEN '2025-04-13'
    WHEN 12 THEN '2025-04-18'
    WHEN 13 THEN '2025-04-20'
    WHEN 14 THEN '2025-04-23'
    WHEN 15 THEN '2025-04-27'
    END
WHEN '2026' THEN CASE competitionid
    WHEN 1 THEN '2026-02-28'
    WHEN 2 THEN '2026-03-01'
    WHEN 3 THEN '2026-03-07'
    WHEN 4 THEN '2026-03-21'
    WHEN 5 THEN '2026-03-25'
    WHEN 6 THEN '2026-03-27'
    WHEN 7 THEN '2026-03-29'
    WHEN 8 THEN '2026-04-01'
    WHEN 9 THEN '2026-04-05'
    WHEN 10 THEN '2026-04-08'
    WHEN 11 THEN '2026-04-12'
    WHEN 12 THEN '2026-04-17'
    WHEN 13 THEN '2026-04-19'
    WHEN 14 THEN '2026-04-22'
    WHEN 15 THEN '2026-04-26'
    END
END, modified = GETDATE()
WHERE competitionid BETWEEN 1 AND 15
AND seasonid = @season_id

UPDATE compseason
SET enddate = DATEADD(ss, -1, DATEADD(dd, 1, startdate)), modified = GETDATE()
WHERE competitionid BETWEEN 1 AND 15
AND seasonid = @season_id
